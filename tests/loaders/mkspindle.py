#!/usr/bin/env python3
# Builds the inputs of the Spindle loader test: seeded random data in jobs loaded to several
# areas, the load script, and a checker (k64asm source) that calls the loader for each job and
# sums what arrived against the sums of the same data. Result through the debug cartridge
# ($D7FF): 0 = every job arrived intact, else the number of the first job that did not.
#   mkspindle.py OUTDIR
import os
import random
import sys

out = sys.argv[1]
rng = random.Random(64)
# Each job: chunks of (address, pages). Avoided: the loader's pages 2-3 and zero page f4-f8,
# the checker at $1000, the screen, I/O, and the vectors at the top of memory.
jobs = [[(0x4000, 0x20)], [(0x8000, 0x20)], [(0x2000, 0x10), (0xc000, 0x10)], [(0xa000, 0x20), (0xe000, 0x10)],
        [(0x6000, 0x08)], [(0x5000, 0x30)]]
script = ["checker.prg", ""]
code = ["; Generated by tests/loaders/mkspindle.py: the Spindle loader test's checker.",
        "ptr = $fb", "cnt = $fd", "lo = $f9", "hi = $fa", "        * = $1000", "        lda #$0b", "        sta $d020"]
for j, chunks in enumerate(jobs, 1):
    code += [f"        jsr $0200               ; job {j}"]
    for n, (addr, pages) in enumerate(chunks):
        data = bytes(rng.randrange(256) for _ in range(pages * 256))
        name = f"j{j}c{n}.bin"
        with open(os.path.join(out, name), "wb") as f:
            f.write(data)
        script.append(f"{name}\t{addr:x}")
        total = sum(data) & 0xffff
        code += [f"        lda #${addr >> 8:02x}", f"        ldx #${pages:02x}", "        jsr sum",
                 "        lda lo", f"        cmp #${total & 0xff:02x}", f"        beq lo{j}_{n}", f"        jmp fail{j}",
                 f"lo{j}_{n}   lda hi", f"        cmp #${total >> 8:02x}", f"        beq hi{j}_{n}", f"        jmp fail{j}",
                 f"hi{j}_{n}"]
    script.append("")
code += ["        lda #0", "        sta $d7ff", "pass    jmp pass"]
for j in range(1, len(jobs) + 1):
    code += [f"fail{j}   lda #{j}", "        sta $d7ff", f"stop{j}   jmp stop{j}"]
code += ["; sum: the 16-bit sum of X pages from page A into lo/hi",
         "sum     sta ptr + 1", "        stx cnt", "        lda #0", "        sta ptr", "        sta lo", "        sta hi",
         "page    ldy #0", "byte    lda (ptr),y", "        clc", "        adc lo", "        sta lo", "        bcc nocarry",
         "        inc hi", "nocarry iny", "        bne byte", "        inc ptr + 1", "        dec cnt", "        bne page",
         "        rts"]
with open(os.path.join(out, "checker.s"), "w") as f:
    f.write("\n".join(code) + "\n")
with open(os.path.join(out, "script"), "w") as f:
    f.write("\n".join(script) + "\n")
