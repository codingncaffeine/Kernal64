#!/usr/bin/env python3
# Our own turbo tape test (hw/tape.md TT): masters a TAP in a typical turbo format and writes
# the loader that reads it (k64asm source). Format: a pilot of SHORT pulses, a LONG pulse,
# the sync byte $A5, then bytes most significant bit first, a SHORT pulse = 0, a LONG = 1:
# load address (2 bytes, low first), length (2 bytes), the data, an XOR checksum. The loader
# times the FLAG edges against CIA 1's timer A running free, as commercial turbos do; result
# through the debug cartridge ($D7FF): 0 = loaded with the right checksum and the data sums
# to what was mastered, 1 = no sync, 2 = bad checksum, 3 = wrong data.
#   mkturbo.py OUTDIR SHORT LONG     (pulse lengths in cycles, e.g. 256 384)
import os
import random
import sys

out, short, long_ = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
rng = random.Random(9)
load, length = 0x4000, 0x2000
data = bytes(rng.randrange(256) for _ in range(length))

pulses = [short] * 2000 + [long_]
def byte(b):
    for k in range(7, -1, -1):
        pulses.append(long_ if (b >> k) & 1 else short)
byte(0xA5)
for b in (load & 0xFF, load >> 8, length & 0xFF, length >> 8):
    byte(b)
x = 0
for b in data:
    byte(b)
    x ^= b
byte(x)
pulses += [short] * 200

tap = bytearray(b"C64-TAPE-RAW" + bytes([1, 0, 0, 0]))
body = bytearray()
for p in pulses:
    if p % 8 == 0 and 1 <= p // 8 <= 255:
        body.append(p // 8)
    else:
        body += bytes([0, p & 0xFF, (p >> 8) & 0xFF, p >> 16])
tap += len(body).to_bytes(4, "little") + body
with open(os.path.join(out, "turbo.tap"), "wb") as f:
    f.write(tap)

threshold = (short + long_) // 2
total = sum(data) & 0xFFFF
src = f"""; Generated by tests/tape/mkturbo.py: our turbo tape loader (pulses {short}/{long_} cycles).
ptr = $fb
chk = $fd
prev = $f7
thl = <{threshold}
thh = >{threshold}
        * = $0801
        .basic
        sei
        lda #$0b                ; screen off: no bad lines to stretch a pulse's timing
        sta $d011
        lda #$7f
        sta $dc0d
        lda $dc0d
        lda #$ff                ; timer A free-running from $FFFF
        sta $dc04
        sta $dc05
        lda #$11
        sta $dc0e
        lda $01                 ; the motor on: port bit 5 low
        and #$df
        sta $01
        lda #$ff
        sta prev
        sta prev + 1
; find the pilot: at least 64 SHORT pulses in a row, then its end: a LONG pulse
pilot   ldx #64
        stx run
short   jsr getbit
        bcs pilot
        dec run
        bne short
sync    jsr getbit
        bcc sync
        jsr byte8
        cmp #$a5
        beq got
        lda #1
        jmp done
got     jsr byte8
        sta ptr
        jsr byte8
        sta ptr + 1
        jsr byte8
        sta len
        jsr byte8
        sta len + 1
        lda #0
        sta chk
        ldy #0
data    jsr byte8
        ldy #0                  ; (getbit uses Y)
        sta (ptr),y
        eor chk
        sta chk
        inc ptr
        bne nohi
        inc ptr + 1
nohi    lda len
        bne declo
        dec len + 1
declo   dec len
        lda len
        ora len + 1
        bne data
        jsr byte8
        cmp chk
        beq sumok
        lda #2
        jmp done
; the data sums to what was mastered
sumok   lda #<{load}
        sta ptr
        lda #>{load}
        sta ptr + 1
        lda #0
        sta sl
        sta sh
        ldx #>{length}
sp      ldy #0
sb      lda (ptr),y
        clc
        adc sl
        sta sl
        bcc sn
        inc sh
sn      iny
        bne sb
        inc ptr + 1
        dex
        bne sp
        lda sl
        cmp #${total & 0xFF:02x}
        bne bad
        lda sh
        cmp #${total >> 8:02x}
        bne bad
        lda #0
        jmp done
bad     lda #3
done    sta $d7ff
stop    jmp stop
; byte8: eight bits, most significant first, into A
byte8   lda #1
        sta acc
b8      jsr getbit
        rol acc
        bcc b8
        lda acc
        rts
; getbit: waits for the next FLAG edge; carry = the pulse was LONG
getbit  lda $dc0d
        and #$10
        beq getbit
        ldx $dc05               ; timer A, high then low
        ldy $dc04
        cpx $dc05               ; read again if the high byte moved under us
        beq same
        ldx $dc05
        ldy $dc04
same    sec                     ; elapsed = prev - now
        tya
        eor #$ff
        adc prev
        sta el
        txa
        eor #$ff
        adc prev + 1
        sta eh
        sty prev
        stx prev + 1
        lda el                  ; carry = elapsed >= threshold
        cmp #thl
        lda eh
        sbc #thh
        rts
len     .byte 0, 0
run     .byte 0
acc     .byte 0
el      .byte 0
eh      .byte 0
sl      .byte 0
sh      .byte 0
"""
with open(os.path.join(out, "turbo.s"), "w") as f:
    f.write(src)
