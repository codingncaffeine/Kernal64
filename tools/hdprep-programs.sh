#!/usr/bin/env bash
# Regenerates src/drive/hdprep/programs.h from the two BASIC sources beside it (tokenized by
# tools/basic2prg.py). --check: exit 1 if the committed header differs from the sources.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
D="$ROOT/src/drive/hdprep"
gen() {
    echo "// Generated by tools/hdprep-programs.sh from partition.bas and format.bas: do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    for n in partition format; do
        echo "inline constexpr uint8_t k${n^}Prg[] = {"
        python3 -I "$ROOT/tools/basic2prg.py" "$D/$n.bas" - | xxd -i | sed 's/^/   /'
        echo "};"
    done
}
if [ "${1:-}" = "--check" ]; then
    diff <(gen) "$D/programs.h" >/dev/null && echo "hdprep programs: header matches the sources" || { echo "hdprep programs: header differs from the sources"; exit 1; }
else
    gen > "$D/programs.h"
fi
